// Builds lang/out/lang_<l>.js from the translated JSON chunks (es/A–D.json + mtx.js).
// Run by build.py:  node lang/pack.js
const fs=require('fs'),path=require('path'); const {load}=require('./extract.js');
const x=load(); const OUT=path.join(__dirname,'out'); fs.mkdirSync(OUT,{recursive:true});
const J=o=>JSON.stringify(o);
// rebuild the nested overlay from flat paths, using the German overlay as the shape
function nest(de,flat,pre){
  if(typeof de==='string') return flat[pre]!=null?flat[pre]:de;
  if(Array.isArray(de)) return de.map((v,i)=>nest(v,flat,pre?pre+'.'+i:String(i)));
  if(de&&typeof de==='object'){ const o={}; for(const k of Object.keys(de)) o[k]=nest(de[k],flat,pre?pre+'.'+k:k); return o; }
  return de;
}
const built=[];
for(const L of ['es','el']){
  const d=path.join(__dirname,L), f=n=>path.join(d,n);
  if(!['A.json','B.json','C.json','D.json','mtx.js'].every(n=>fs.existsSync(f(n)))){ try{fs.unlinkSync(path.join(OUT,'lang_'+L+'.js'));}catch(e){} continue; }
  const A=JSON.parse(fs.readFileSync(f('A.json'))), B=JSON.parse(fs.readFileSync(f('B.json'))),
        C=JSON.parse(fs.readFileSync(f('C.json'))), D=JSON.parse(fs.readFileSync(f('D.json')));
  const O=nest(x.DE,B,'');
  let s=`/* ${L} language pack — generated by lang/pack.js from lang/${L}/*.json; edit those, not this */\n`;
  s+=`var LPACK=window.LPACK||(window.LPACK={}), LPX=window.LPX||(window.LPX={}), MGX=window.MGX||(window.MGX={});\n`;
  s+=`STR.${L}=${J(A.STR)};\n`;
  s+=fs.readFileSync(f('mtx.js'),'utf8')+'\n';
  s+=`LPACK.${L}={O:${J(O)},BQ:${J(C.BQ)},VQ:${J(C.VQ)},VOCAB:${J(A.VOCAB)},SPELL:${J(A.SPELL)},GROUPS:${J(A.GROUPS)},BOOKS:${J(A.BOOKS)},BOOK:${J(A.BOOK)},STORY:${J(A.STORY)},fallbackVerse:${J(A.MISC.fallbackVerse)},bookOpts:${J(A.MISC.bookOpts)}};\n`;
  s+=`QX.${L}=${J(D.QX)};\nCHOICES.${L}=${J(D.CHOICES)};\n`;
  s+=`(function(p){ for(var k in p) if(PLACES[k]) PLACES[k].${L}=p[k]; })(${J(D.PLACES)});\n`;
  s+=`MGX.${L}=${J(A.MG)};\n`;
  fs.writeFileSync(path.join(OUT,'lang_'+L+'.js'),s); built.push(L+' '+Math.round(s.length/1024)+'KB');
}
console.log('language packs:',built.join(', ')||'none');
